"""S1 gate: the five app-owned stores live under ``$TDTB_HOME/state/``.

S1 moves runstate, the tag-exclusion policy, the Capacities settings, the
Capacities source record and the deferrals log out of the Obsidian vault into
the machine-local app home (``app_config.state_dir()``). The contract these
tests pin:

  - every store resolves to the new path by default;
  - a read prefers the new path and falls back READ-ONLY to the frozen vault
    copy, so S1 is reversible;
  - a write always lands at the new path and leaves every vault byte
    untouched;
  - ``TDTB_HOME`` relocates the whole state tree.

Everything here is fixture-only: ``tmp_path`` is the vault root, the autouse
``_isolated_app_home`` fixture in ``conftest.py`` points ``TDTB_HOME`` at a
private tmp dir, and no test reads or writes the operator's real vault.
"""
from __future__ import annotations

import json
import sys
from datetime import date
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).parent.parent))

import app_config  # noqa: E402
import capacities_builder as cb  # noqa: E402
import capacities_settings as cs  # noqa: E402
import deferrals as df  # noqa: E402
import exclusion_settings as es  # noqa: E402
import runstate  # noqa: E402


SPACE = "space-1"
TAG_A = "5a25370b-f9a0-40cf-bc3a-0cab4744913c"
DAY = date(2026, 10, 8)
PRIOR_DAY = date(2026, 10, 7)

#: The pre-S1 vault cache directory. Every legacy fixture below lives here and
#: must still be byte-identical after a write.
LEGACY_CACHE_REL = Path("00 - META/Cache")


# ---------------------------------------------------------------------------
# Fixtures
# ---------------------------------------------------------------------------

def _runstate_note(anchor: str, on_day: date = DAY) -> str:
    """A pre-S1 ``tdtb-runstate-<day>.md`` note (frontmatter + fenced JSON)."""
    return "\n".join([
        "---",
        f"valid_date: '{on_day}'",
        "written_at: '2026-10-07T00:00:00Z'",
        "---",
        "",
        "```json",
        json.dumps({"anchor": anchor, "eod": "11:59 PM"}),
        "```",
        "",
    ])


def _recent_selections_note(selection_id: str) -> str:
    return "\n".join([
        "---",
        "runs:",
        f"  - date: '{PRIOR_DAY}'",
        "    selections:",
        f'      - id: "{selection_id}"',
        '        path: "legacy.md"',
        "        blocks: 1",
        "---",
        "",
        "_Auto-generated by runstate.py. Do not edit manually._",
        "",
    ])


def _digest_index_payload(items: list[dict]) -> dict:
    return {"valid_date": str(DAY), "items": items}


def _exclusions_payload(revision: int, tag_id: str = TAG_A) -> dict:
    return {
        "version": 1,
        "revision": revision,
        "exclusions": {
            "tags": [{"source": "capacities", "space_id": SPACE, "tag_id": tag_id}],
        },
    }


def _capacities_settings_payload(revision: int) -> dict:
    return {
        "version": 1,
        "revision": revision,
        "native_task_auto": {
            "active_enabled": True,
            "due_enabled": True,
            "deadline_enabled": True,
            "deadline_horizon_days": 2,
        },
        "excluded": {},
        "active_structures": {},
    }


def _capacities_source_payload(revision: int) -> dict:
    return {
        "version": 1,
        "revision": revision,
        "space_id": SPACE,
        "structures": [{"structure_id": "RootTask"}],
    }


def _deferrals_payload(items: dict) -> dict:
    return {"version": 1, "items": items}


def _deferral_entry(count: int = 2, todoist_id: str = "42") -> dict:
    return {
        "count": count,
        "last_deferred": str(PRIOR_DAY),
        "name": "Legacy",
        "path": "",
        "todoist_id": todoist_id,
    }


#: Legacy vault file name -> bytes written by :func:`_seed_legacy_vault`. Every
#: one of the five stores is represented, plus the two runtime lock artifacts
#: that must never be migrated.
def _legacy_files(tag_id: str = TAG_A) -> dict[str, str]:
    return {
        f"tdtb-runstate-{DAY}.md": _runstate_note("legacy-anchor"),
        "tdtb-recent-selections.md": _recent_selections_note("legacy-1"),
        f"tdtb-digest-index-{DAY}.json": json.dumps(
            _digest_index_payload([{"name": "Legacy", "todoist_id": "", "path": "legacy.md"}])
        ),
        "tdtb-exclusion-settings.json": json.dumps(_exclusions_payload(3, tag_id)),
        "tdtb-capacities-settings.json": json.dumps(_capacities_settings_payload(5)),
        "tdtb-capacities-source.json": json.dumps(_capacities_source_payload(2)),
        "tdtb-deferrals.json": json.dumps(
            _deferrals_payload({"todoist:42": _deferral_entry()})
        ),
        "tdtb-exclusion-settings.lock": "",
        "tdtb-capacities-settings.lock": "",
        "tdtb-capacities-source.lock": "",
    }


def _seed_legacy_vault(vault: Path, tag_id: str = TAG_A) -> dict[str, bytes]:
    """Write the pre-S1 vault cache. Returns name -> bytes for later comparison."""
    cache = vault / LEGACY_CACHE_REL
    cache.mkdir(parents=True, exist_ok=True)
    written: dict[str, bytes] = {}
    for name, text in _legacy_files(tag_id).items():
        target = cache / name
        target.write_text(text, encoding="utf-8")
        written[name] = target.read_bytes()
    return written


def _snapshot(root: Path) -> dict[str, bytes]:
    """Every file under ``root`` as relpath -> bytes (the "nothing changed" probe)."""
    return {
        str(path.relative_to(root)): path.read_bytes()
        for path in sorted(root.rglob("*"))
        if path.is_file()
    }


@pytest.fixture
def vault(tmp_path: Path) -> Path:
    root = tmp_path / "vault-root"
    root.mkdir()
    return root


@pytest.fixture
def legacy(vault: Path) -> dict[str, bytes]:
    return _seed_legacy_vault(vault)


# ---------------------------------------------------------------------------
# 1. Every store resolves under the state dir
# ---------------------------------------------------------------------------

def test_every_store_path_is_under_the_state_dir(tmp_path: Path, monkeypatch) -> None:
    home = tmp_path / "home"
    monkeypatch.setenv("TDTB_HOME", str(home))
    state = home / "state"

    assert app_config.state_dir() == state
    assert runstate.state_runstate_dir() == state / "runstate"
    assert runstate.state_runstate_path(DAY) == state / "runstate" / f"tdtb-runstate-{DAY}.md"
    assert (
        runstate.state_recent_selections_path()
        == state / "runstate" / "tdtb-recent-selections.md"
    )
    assert (
        runstate.state_digest_index_path(DAY)
        == state / "runstate" / f"tdtb-digest-index-{DAY}.json"
    )
    assert es.settings_path() == state / "exclusions.json"
    assert cs.settings_path() == state / "capacities-settings.json"
    assert cb.source_path() == state / "capacities-source.json"
    assert df.deferrals_path() == state / "deferrals.json"

    # Locks are runtime artifacts at the new location, never in the vault.
    assert es.lock_path() == state / "exclusions.lock"
    assert cs.lock_path() == state / "capacities-settings.lock"
    assert cb.lock_path() == state / "capacities-source.lock"

    for path in (
        runstate.state_runstate_path(DAY),
        es.settings_path(),
        cs.settings_path(),
        cb.source_path(),
        df.deferrals_path(),
    ):
        assert path.is_relative_to(state)


def test_resolving_a_path_creates_nothing(vault: Path) -> None:
    assert not es.settings_path().exists()
    assert not cs.settings_path().exists()
    assert not cb.source_path().exists()
    assert not df.deferrals_path().exists()
    assert not runstate.state_runstate_dir().exists()
    assert _snapshot(vault) == {}


