def test_all_stores_read_the_legacy_vault_with_no_state_files(
    vault: Path, legacy: dict[str, bytes]
) -> None:
    assert runstate.read_runstate(vault, DAY) == {"anchor": "legacy-anchor", "eod": "11:59 PM"}
    assert runstate.read_recent_selections(vault)[0]["selections"][0]["id"] == "legacy-1"
    assert runstate.read_digest_index(vault, DAY)[0]["name"] == "Legacy"
    assert es.read_settings(vault).settings.revision == 3
    assert cs.read_settings(vault).settings.revision == 5
    assert cb.read_source(vault).revision == 2
    assert df.load_deferrals(vault)["todoist:42"]["count"] == 2

    # A fallback read is read-only: the vault snapshot is untouched.
    assert _snapshot(vault)[str(LEGACY_CACHE_REL / "tdtb-runstate-2026-10-08.md")] == (
        legacy["tdtb-runstate-2026-10-08.md"]
    )


def test_all_stores_prefer_the_state_copy_when_both_exist(
    vault: Path, legacy: dict[str, bytes]
) -> None:
    runstate.state_runstate_path(DAY).parent.mkdir(parents=True, exist_ok=True)
    runstate.state_runstate_path(DAY).write_text(_runstate_note("state-anchor"), encoding="utf-8")
    runstate.state_recent_selections_path().write_text(
        _recent_selections_note("state-1"), encoding="utf-8"
    )
    runstate.state_digest_index_path(DAY).write_text(
        json.dumps(_digest_index_payload([{"name": "State"}])), encoding="utf-8"
    )
    es.settings_path().parent.mkdir(parents=True, exist_ok=True)
    es.settings_path().write_text(
        json.dumps(_exclusions_payload(9, TAG_A)), encoding="utf-8"
    )
    cs.settings_path().write_text(json.dumps(_capacities_settings_payload(11)), encoding="utf-8")
    cb.source_path().write_text(json.dumps(_capacities_source_payload(13)), encoding="utf-8")
    df.deferrals_path().write_text(
        json.dumps(_deferrals_payload({"todoist:99": _deferral_entry(7, "99")})),
        encoding="utf-8",
    )

    assert runstate.read_runstate(vault, DAY)["anchor"] == "state-anchor"
    assert runstate.read_recent_selections(vault)[0]["selections"][0]["id"] == "state-1"
    assert runstate.read_digest_index(vault, DAY)[0]["name"] == "State"
    assert es.read_settings(vault).settings.revision == 9
    assert cs.read_settings(vault).settings.revision == 11
    assert cb.read_source(vault).revision == 13
    assert df.load_deferrals(vault)["todoist:99"]["count"] == 7

    # The vault copies are still exactly the pre-S1 bytes.
    cache = vault / LEGACY_CACHE_REL
    for name, raw in legacy.items():
        assert (cache / name).read_bytes() == raw


def test_legacy_and_state_path_helpers_point_at_different_files(vault: Path) -> None:
    assert es.legacy_settings_path(vault) == vault / LEGACY_CACHE_REL / "tdtb-exclusion-settings.json"
    assert cs.legacy_settings_path(vault) == vault / LEGACY_CACHE_REL / "tdtb-capacities-settings.json"
    assert cb.legacy_source_path(vault) == vault / LEGACY_CACHE_REL / "tdtb-capacities-source.json"
    assert df.legacy_deferrals_path(vault) == vault / LEGACY_CACHE_REL / "tdtb-deferrals.json"
    assert (
        runstate.legacy_runstate_path(vault, DAY)
        == vault / LEGACY_CACHE_REL / f"tdtb-runstate-{DAY}.md"
    )


# ---------------------------------------------------------------------------
# 4. Writes land at the new path; the vault copy is untouched
# ---------------------------------------------------------------------------

def test_runstate_write_lands_in_state_and_leaves_the_vault_untouched(
    vault: Path, legacy: dict[str, bytes]
) -> None:
    before = _snapshot(vault)
    written = runstate.write_runstate(
        vault, DAY, {**runstate.build_runstate(), "anchor": "state-anchor"}
    )

    assert written == runstate.state_runstate_path(DAY)
    assert written.is_file()
    assert runstate.read_runstate(vault, DAY)["anchor"] == "state-anchor"
    assert _snapshot(vault) == before
    # The frozen vault note still holds the pre-S1 value.
    assert (
        vault / LEGACY_CACHE_REL / f"tdtb-runstate-{DAY}.md"
    ).read_bytes() == legacy[f"tdtb-runstate-{DAY}.md"]


def test_runstate_cleanup_never_deletes_a_vault_note(
    vault: Path, legacy: dict[str, bytes]
) -> None:
    """Trigger-1 cleanup prunes earlier-dated notes in the ACTIVE directory
    only — the frozen vault history is the rollback point."""
    stale = vault / LEGACY_CACHE_REL / "tdtb-runstate-2026-10-01.md"
    stale.write_text(_runstate_note("older", date(2026, 10, 1)), encoding="utf-8")
    before = _snapshot(vault)

    runstate.write_runstate(vault, DAY, runstate.build_runstate())

    assert stale.read_bytes() == before[str(LEGACY_CACHE_REL / stale.name)]
    assert _snapshot(vault) == before


def test_recent_selections_write_lands_in_state_and_keeps_the_vault_copy(
    vault: Path, legacy: dict[str, bytes]
) -> None:
    before = _snapshot(vault)

    written = runstate.append_recent_selection(
        vault, DAY, [{"id": "state-1", "path": "state.md", "blocks": 2}]
    )

    assert written == runstate.state_recent_selections_path()
    runs = runstate.read_recent_selections(vault)
    assert runs[0]["selections"][0]["id"] == "state-1"
    # The prior vault run is carried forward, not lost.
    assert runs[1]["selections"][0]["id"] == "legacy-1"
    assert _snapshot(vault) == before


